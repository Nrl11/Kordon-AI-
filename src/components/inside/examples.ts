export const STEPS = ["Запрос", "Поиск", "Маскирование", "Маршрут", "Ответ"] as const;
export type Step = 0 | 1 | 2 | 3 | 4;

export function caption(step: Step, e: Example) {
  switch (step) {
    case 0:
      return "Сотрудник пишет как обычно — в свой чат или через API. Запрос идёт через Кордон.";
    case 1:
      return "Кордон разбирает текст: ищет персданные, ключи и закрытые документы.";
    case 2:
      return e.closed
        ? "Закрытое не маскируется — оно просто не выйдет из контура."
        : "Маскирование: найденное заменяется метками. Оригинал остаётся у вас.";
    case 3:
      return e.closed
        ? "Закрытое во внешние модели не отправляется — запрос уходит в локальную модель внутри контура."
        : "После маскирования запрос можно отправить наружу — во внешнюю модель.";
    default:
      return e.closed
        ? "Ответ локальной модели — запрос не покидал компанию."
        : "Ответ приходит с метками — Кордон возвращает данные на место.";
  }
}
