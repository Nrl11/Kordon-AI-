/* Примеры для блока «Что Кордон делает с запросом». Каждое слово — плитка.
   У чувствительных кусков — вид: персданные и секреты маскируются меткой,
   закрытое не маскируется, а просто не выходит из контура. */

export type Kind = "pii" | "secret" | "closed";
export interface Word {
  t: string;
  kind?: Kind;
  label?: string; // подпись над найденным куском
  token?: string; // метка, которую видит модель
  glue?: boolean; // прилипает к предыдущему слову (знаки препинания)
}
export interface Row {
  k: string;
  v: string;
  tone: "gold" | "blue" | "green";
}
export interface Example {
  tab: string;
  who: string;
  req: Word[];
  ans: Word[];
  rows: Row[];
  closed?: boolean;
  model: number; // в какую из внешних моделей уйдёт запрос (на схеме они без имён)
}

const w = (s: string): Word[] =>
  s
    .split(" ")
    .filter(Boolean)
    .map((t) => (/^[,.:;)]+$/.test(t) ? { t, glue: true } : { t }));

